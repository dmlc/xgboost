# Configure R package builds to use sccache.
#
# Pass --cmake to configure CMake launchers instead,to avoid selecting an sccache-wrapped
# CXX as NVCC's host compiler.

args <- commandArgs(trailingOnly = TRUE)
if (length(args) > 1L || (length(args) == 1L && args[[1L]] != "--cmake")) {
  stop("Usage: setup_r_sccache.R [--cmake]", call. = FALSE)
}
use_cmake <- length(args) == 1L
header <- "# Generated by XGBoost CI setup_r_sccache.R"

makevars <- file.path(path.expand("~"), ".R", "Makevars")
if (file.exists(makevars)) {
  first_line <- readLines(makevars, n = 1L, warn = FALSE)
  if (!identical(first_line, header)) {
    stop(
      makevars,
      " already exists; aborting to avoid overwriting it.",
      call. = FALSE
    )
  }
}

dir.create(dirname(makevars), recursive = TRUE, showWarnings = FALSE)
if (use_cmake) {
  settings <- c(
    header,
    "CMAKE_C_COMPILER_LAUNCHER = sccache",
    "CMAKE_CXX_COMPILER_LAUNCHER = sccache",
    "CMAKE_CUDA_COMPILER_LAUNCHER = sccache"
  )
} else {
  settings <- c(
    header,
    "CC := sccache $(CC)",
    "CXX := sccache $(CXX)",
    "CXX11 := sccache $(CXX11)",
    "CXX14 := sccache $(CXX14)",
    "CXX17 := sccache $(CXX17)",
    "CXX20 := sccache $(CXX20)"
  )
}
# Source-root normalization applies to both compiler wrappers and CMake launchers.
if (.Platform$OS.type != "windows") {
  settings <- c(
    settings,
    "",
    "# R CMD build installs under a random Rbuild directory for vignettes.",
    "# Normalize that source root before hashing; sccache reads it at server startup.",
    "# Keep R's default target and restart only for XGBoost's CMake build.",
    "all:",
    ".PHONY: xgboost-ci-sccache",
    "xgboost-cmake: xgboost-ci-sccache",
    "xgboost-ci-sccache:",
    "# A missing server is harmless; preserve other shutdown failures.",
    "\t@status=0; output=$$(LC_ALL=C sccache --stop-server 2>&1) || status=$$?; \\",
    "\tprintf '%s\\n' \"$$output\"; \\",
    "\tcase \"$$output\" in \\",
    "\t  *'Connection refused (os error 61)'*|*'Connection refused (os error 111)'*) ;; \\",
    "\t  *) exit $$status ;; \\",
    "\tesac",
    "# R CMD check can set TMPDIR beyond the Unix socket path limit on macOS.",
    "\tTMPDIR=/tmp SCCACHE_BASEDIRS=\"$(CURDIR)\" sccache --start-server"
  )
}
writeLines(settings, makevars)
